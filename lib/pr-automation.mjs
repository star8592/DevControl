export class PRAutomation {
  constructor({ provider = 'github' } = {}) {
    this.provider = provider;
  }

  buildCandidate({ project, repairResult }) {
    return {
      provider: this.provider,
      project: project?.key || null,
      branch: repairResult?.branch || null,
      baseSha: repairResult?.baseSha || null,
      repairSha: repairResult?.repairSha || null,
      status: repairResult?.status || 'UNKNOWN',
      ready: repairResult?.status === 'CANDIDATE_READY'
    };
  }

  createDraftPayload(candidate) {
    return {
      title: `fix: DevControl automated repair ${candidate.project || 'project'}`,
      body: [
        'Generated by DevControl repair pipeline.',
        '',
        `Project: ${candidate.project || '-'}`,
        `Branch: ${candidate.branch || '-'}`,
        `Repair SHA: ${candidate.repairSha || '-'}`,
        '',
        'Validation must be reviewed before merge.'
      ].join('\n'),
      draft: true
    };
  }
}

export default PRAutomation;
